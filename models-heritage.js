// 擴充模型：歷史建築（日式屋舍、城門、八角樓、軍艦）
// 由主檔 models.js 的 buildModel 分派：回傳 true 表示已處理，false 表示不是這裡的模型。
// h 內的工具（單位空間：底面約 [-0.5, 0.5]，y 向上，1 單位 ≈ 模型縮放前的一格）：
//   h.box(pos, size, color, rot?)   方塊            h.b(pos, size, color, rot?)   圓角方塊（小於 0.06 會退回方塊）
//   h.cy(pos, r, height, color, rot?) 圓柱           h.cone(pos, r, height, color) 圓錐
//   h.sphere(pos, r, color)         球              h.dome(pos, r, height, color) 半球
//   h.ring(pos, r, color, rot?)     環              h.hip(pos, size, color)       四角屋頂（底面 1×1，位置是屋頂中心）
//   h.glow(pos, size, color?, rot?) 發光方塊（夜晚亮）  h.glass(pos, size, color?)   玻璃
//   h.post(x, z, height, color?, r?) 立柱            h.windows(y, z, n, span?, w?, hgt?) 一排窗
//   h.bench(x, z, ry?) 長椅         h.plant(x, z, k?) 樹   h.tree(x, z, k, kind?) 樹（kind "cone"/"round"）
//   h.p(kind, pos, size, color, rot?) 任意零件（kind 見 kit.js）
//   h.C 調色盤（cream, ink, coral, yellow, stone, wood, green, teal, white, window, glass, leaf, dark, sand）、h.accent 該區主色
// rot 為 Euler [x, y, z]，任何軸都可以（主檔會正確合成整體朝向）。
const WOOD_DARK = 0x6b4a36, WOOD_MID = 0x8a6a4a, WOOD_POST = 0x4a3426; // 日式木構：深、中、柱
const TILE = 0x4a4e55, RIDGE = 0x33363b, PAPER = 0xfff2d6; // 灰瓦、屋脊、紙門
const PI = Math.PI;

export function heritageModels(kind, h) {
  const { box, cy, hip, glow, sphere, p, C, accent } = h;
  switch (kind) {
    // ── 日式木造建築：高架地板、深簷寄棟屋頂、縁側、石燈籠與松樹 ──
    case "jphouse": {
      box([0, 0.015, 0], [1.4, 0.03, 1.2], 0xd9d2c6); // 碎石庭院
      box([0.1, 0.035, 0.34], [0.14, 0.02, 0.1], C.stone); // 踏石小徑
      box([0.14, 0.035, 0.46], [0.14, 0.02, 0.1], C.stone);
      box([0.1, 0.035, 0.56], [0.14, 0.02, 0.08], C.stone);
      for (const x of [-0.45, 0, 0.45]) for (const z of [-0.3, 0.2]) cy([x, 0.06, z], 0.02, 0.12, WOOD_POST); // 床下短柱
      box([0, 0.14, -0.05], [1.0, 0.04, 0.6], WOOD_MID); // 高架地板（前緣即縁側）
      box([0, 0.36, -0.1], [0.9, 0.4, 0.46], WOOD_DARK); // 木板牆
      for (const x of [-0.46, -0.15, 0.15, 0.46]) cy([x, 0.36, 0.23], 0.012, 0.4, WOOD_POST); // 縁側細柱
      for (const x of [-0.3, 0, 0.3]) glow([x, 0.36, 0.137], [0.24, 0.3, 0.01], PAPER); // 紙拉門
      h.windows(0.4, -0.337, 2, 0.5); // 後側窗
      hip([0, 0.7, -0.1], [1.22, 0.3, 0.78], TILE); // 深簷灰瓦寄棟屋頂
      box([0, 0.845, -0.1], [0.5, 0.04, 0.07], RIDGE); // 大棟
      box([0, 0.49, 0.235], [0.22, 0.1, 0.01], accent); // 入口暖簾
      box([0.1, 0.07, 0.29], [0.2, 0.08, 0.1], C.stone); // 沓脱石
      cy([0.55, 0.05, 0.42], 0.06, 0.04, C.stone); // 石燈籠：基座、竿、火袋、笠
      cy([0.55, 0.14, 0.42], 0.02, 0.14, C.stone);
      box([0.55, 0.25, 0.42], [0.1, 0.08, 0.1], 0xa09488);
      p("glow", [0.55, 0.25, 0.42], [0.05, 0.05, 0.12], 0xffd9a0);
      hip([0.55, 0.32, 0.42], [0.16, 0.06, 0.16], C.stone);
      h.tree(-0.58, 0.42, 0.45, "cone"); // 松樹
      sphere([0.4, 0.06, 0.55], 0.06, C.leaf); // 庭園矮灌木
      return true;
    }
    // ── 清代城門（大東門）：石砌城牆、拱形門洞、雉堞、兩層重簷城樓 ──
    case "gate": {
      box([0, 0.21, 0], [1.4, 0.42, 0.5], 0x8a7d6e); // 城牆
      box([0, 0.36, 0], [1.41, 0.1, 0.51], 0x9c7a62); // 上層磚砌帶
      box([0, 0.11, 0], [0.26, 0.22, 0.58], C.ink); // 門洞（下半）
      p("cylinder", [0, 0.22, 0], [0.26, 0.58, 0.26], C.ink, [PI / 2, 0, 0]); // 門洞拱頂
      for (const z of [-0.262, 0.262]) p("cylinder", [0, 0.22, z], [0.36, 0.02, 0.36], 0xb9ab98, [PI / 2, 0, 0]); // 拱券石框
      for (const z of [-0.235, 0.235]) {
        box([0, 0.44, z], [1.4, 0.04, 0.03], 0x8a7d6e); // 女牆
        for (const x of [-0.6, -0.3, 0.3, 0.6]) box([x, 0.49, z], [0.12, 0.07, 0.03], 0x8a7d6e); // 雉堞
      }
      box([0, 0.6, 0], [0.56, 0.36, 0.32], WOOD_DARK); // 城樓一層
      for (const x of [-0.3, 0.3]) for (const z of [-0.17, 0.17]) cy([x, 0.5975, z], 0.025, 0.365, 0xb8412f); // 紅柱
      for (const z of [-0.167, 0.167]) glow([0, 0.6, z], [0.36, 0.12, 0.01]);
      hip([0, 0.84, 0], [0.9, 0.14, 0.6], TILE); // 下簷
      box([0, 0.83, 0], [0.6, 0.03, 0.4], WOOD_MID); // 二層平座
      for (const z of [-0.2, 0.2]) box([0, 0.865, z], [0.6, 0.04, 0.015], C.ink); // 欄杆
      box([0, 0.985, 0], [0.44, 0.28, 0.26], WOOD_DARK); // 城樓二層
      for (const x of [-0.24, 0.24]) for (const z of [-0.145, 0.145]) cy([x, 0.985, z], 0.02, 0.28, 0xb8412f);
      for (const z of [-0.137, 0.137]) glow([0, 1.0, z], [0.26, 0.1, 0.01]);
      hip([0, 1.21, 0], [0.76, 0.2, 0.5], TILE); // 上簷
      box([0, 1.31, 0], [0.4, 0.04, 0.06], RIDGE); // 正脊
      cy([0.62, 0.72, -0.18], 0.012, 0.62, C.ink); // 旗竿
      box([0.68, 0.96, -0.18], [0.12, 0.08, 0.01], accent); // 旗
      return true;
    }
    // ── 鹽水八角樓：兩層八角形木樓，四片轉角木板疊出正八角形 ──
    case "octagon": {
      // 正八角形 = 四塊同尺寸長板（長 2r、寬 0.828r）各轉 0°/45°/90°/135° 的聯集
      const oct = (y, hgt, r, color, fn = box) => {
        for (let k = 0; k < 4; k++) fn([0, y, 0], [2 * r, hgt, 0.828 * r], color, [0, (k * PI) / 4, 0]);
      };
      box([0, 0.02, 0], [1.2, 0.04, 1.1], C.stone); // 騎樓地面
      oct(0.235, 0.41, 0.32, WOOD_DARK); // 一樓
      for (let k = 0; k < 4; k++) glow([0, 0.36, 0], [0.656, 0.08, 0.22], PAPER, [0, (k * PI) / 4, 0]); // 一樓窗帶
      glow([0, 0.17, 0.332], [0.2, 0.22, 0.02]); // 一樓店面
      box([0, 0.31, 0.39], [0.3, 0.02, 0.16], accent, [0.35, 0, 0]); // 店面雨遮
      p("glowsphere", [0.11, 0.25, 0.44], [0.05, 0.07, 0.05], 0xff6b3d); // 燈籠
      box([0, 0.05, 0.4], [0.26, 0.03, 0.14], C.stone); // 門前踏階
      for (let k = 0; k < 4; k++) box([0, k ? 0.457 : 0.46, 0], [0.84, k ? 0.034 : 0.04, 0.348], WOOD_MID, [0, (k * PI) / 4, 0]); // 二樓外廊樓板
      p("torus", [0, 0.57, 0], [0.8, 0.8, 0.5], WOOD_MID, [PI / 2, 0, 0]); // 外廊欄杆
      for (let k = 0; k < 8; k++) {
        const a = ((k + 0.5) * PI) / 4;
        cy([0.39 * Math.cos(a), 0.52, 0.39 * Math.sin(a)], 0.012, 0.08, C.ink); // 欄杆柱
      }
      oct(0.675, 0.41, 0.3, WOOD_DARK); // 二樓
      for (let k = 0; k < 4; k++) glow([0, 0.72, 0], [0.616, 0.1, 0.2], PAPER, [0, (k * PI) / 4, 0]); // 二樓窗帶
      p("cone", [0, 1.0, 0], [0.92, 0.26, 0.92], TILE); // 八角攢尖屋頂
      sphere([0, 1.145, 0], 0.035, C.ink); // 寶頂
      return true;
    }
    // ── 德陽艦：退役驅逐艦博物館，船身沿本地 x 軸，艦艏朝 +x，碼頭在 +z 側 ──
    case "ship": {
      const HULL = 0x7f8a94, DECK = 0xa9b2ba, SUPER = 0x8e99a3, STACK = 0x6b757f;
      p("cylinder", [0, 0.0125, 0], [1.7, 0.025, 1.0], 0x5f9bbf); // 水面
      box([0, 0.11, 0], [1.1, 0.18, 0.3], HULL); // 船身
      box([0, 0.035, 0], [1.11, 0.03, 0.31], 0x8c3a2f); // 水線紅漆
      p("cone", [0.695, 0.11, 0], [0.18, 0.3, 0.3], HULL, [0, 0, -PI / 2]); // 尖艏
      box([0, 0.21, 0], [1.1, 0.02, 0.3], DECK); // 主甲板
      box([0.4, 0.235, 0], [0.3, 0.03, 0.28], DECK); // 艏樓甲板
      box([-0.05, 0.3, 0], [0.5, 0.16, 0.2], SUPER); // 上層結構
      box([0.095, 0.43, 0], [0.2, 0.1, 0.18], SUPER); // 艦橋
      glow([0.2, 0.44, 0], [0.012, 0.04, 0.14], 0x9fd8ff); // 艦橋窗
      for (const z of [-0.092, 0.092]) glow([0.095, 0.44, z], [0.14, 0.03, 0.01], 0x9fd8ff);
      cy([-0.18, 0.46, 0], 0.04, 0.16, STACK); // 煙囪
      cy([-0.18, 0.55, 0], 0.045, 0.02, C.ink);
      cy([-0.02, 0.59, 0], 0.012, 0.42, C.ink); // 桅杆
      box([-0.02, 0.66, 0], [0.02, 0.015, 0.22], C.ink); // 橫桁
      h.ring([-0.02, 0.78, 0], 0.06, 0xc9d1d8, [0, PI / 2, 0]); // 雷達
      cy([0.42, 0.285, 0], 0.07, 0.07, HULL); // 前砲塔
      box([0.55, 0.3, 0], [0.2, 0.02, 0.02], C.ink);
      cy([-0.42, 0.255, 0], 0.07, 0.07, HULL); // 後砲塔
      box([-0.55, 0.27, 0], [0.2, 0.02, 0.02], C.ink);
      for (const z of [-0.157, 0.157]) box([0.42, 0.12, z], [0.08, 0.05, 0.01], C.white); // 舷號
      for (const z of [-0.12, 0.12]) box([-0.15, 0.4, z], [0.14, 0.04, 0.05], C.white); // 救生艇
      cy([-0.5, 0.3, 0], 0.008, 0.16, C.ink); // 艦艉旗竿
      box([-0.47, 0.35, 0], [0.06, 0.04, 0.006], C.coral);
      box([-0.1, 0.08, 0.3], [1.1, 0.04, 0.16], C.wood); // 碼頭木棧道
      for (const x of [-0.6, -0.1, 0.4]) cy([x, 0.045, 0.3], 0.015, 0.09, WOOD_DARK); // 棧橋樁
      box([0.15, 0.16, 0.225], [0.08, 0.015, 0.19], C.wood, [0.675, 0, 0]); // 登艦舷梯
      cy([-0.55, 0.17, 0.36], 0.01, 0.34, C.ink); // 碼頭路燈
      p("glowsphere", [-0.55, 0.36, 0.36], [0.045, 0.045, 0.045], C.window);
      cy([0.3, 0.14, 0.36], 0.008, 0.12, C.ink); // 園區指示牌
      box([0.3, 0.2, 0.36], [0.14, 0.08, 0.01], accent);
      return true;
    }
    // ── 鹿陶洋江家聚落：中軸四進（拜亭、公廳、神明廳、祖祠堂）加兩側一排排橫屋，紅磚灰瓦的閩南式農村聚落 ──
    case "jiangvillage": {
      const RED = 0xb4553c, TILE_R = 0x6e3b2e, YARD = 0xd8c7a6;
      h.box([0, 0.012, 0], [1.34, 0.024, 1.14], YARD); // 埕（曬穀、走動的廣場）
      // 中軸四進：越後面越高（公廳、神明廳、祖祠堂）
      [[0.32, 0.18, 0.1], [0.12, 0.22, 0.12], [-0.1, 0.26, 0.12], [-0.32, 0.3, 0.12]].forEach(([z, hgt, d], k) => {
        const w = k === 0 ? 0.2 : 0.34;
        h.b([0, hgt / 2 + 0.02, z], [w, hgt, d], k === 0 ? 0x8b4a32 : RED);
        h.p("hip", [0, hgt + 0.06, z], [w + 0.06, 0.09, d + 0.05], TILE_R);
        h.box([0, hgt + 0.11, z], [w + 0.08, 0.012, 0.012], 0x3a2a24); // 屋脊（燕尾簡化）
        if (k) h.box([0, 0.08, z + d / 2 + 0.003], [0.06, 0.1, 0.006], 0x3a2a24); // 門
      });
      // 兩側橫屋：每側三排長條屋，屋前一排窗
      for (const side of [-1, 1]) for (let r = 0; r < 3; r++) {
        const x = side * (0.3 + r * 0.12);
        h.b([x, 0.1, -0.02], [0.08, 0.16, 0.86], RED);
        h.p("hip", [x, 0.22, -0.02], [0.11, 0.07, 0.9], TILE_R);
        for (let k = -3; k <= 3; k++) h.glow([x - side * 0.042, 0.11, -0.02 + k * 0.11], [0.004, 0.04, 0.04]);
      }
      // 曬衣竿與水缸
      for (const x of [-0.16, 0.16]) h.p("cylinder", [x, 0.1, 0.5], [0.01, 0.2, 0.01], 0x8a6a4a);
      h.box([0, 0.19, 0.5], [0.32, 0.006, 0.006], 0x8a6a4a);
      [0xe9d8a6, 0x6f9fd8, 0xd86f6f].forEach((c, k) => h.box([-0.1 + k * 0.1, 0.15, 0.5], [0.06, 0.07, 0.004], c));
      h.p("cylinder", [0.22, 0.05, 0.42], [0.07, 0.08, 0.07], 0x5a4632);
      h.plant(-0.55, 0.48, 0.28); h.plant(0.56, 0.48, 0.26);
      return true;
    }
    default:
      return false;
  }
}
